/**
 * รูปที่ผู้ใช้เลือกจากคลังภาพในหน้า "เพิ่มรายการใหม่" ส่งต่อไปหน้าครอบรูป
 *
 * ต้องเปิดตัวเลือกไฟล์จากหน้าแรกเลย (เบราว์เซอร์บนมือถือยอมให้เปิดเฉพาะตอนผู้ใช้กดเท่านั้น
 * เปิดเองหลังเปลี่ยนหน้าไม่ได้) จึงฝากไฟล์ไว้ที่นี่ระหว่างเปลี่ยนหน้า — อยู่ในหน่วยความจำ
 * อย่างเดียว รีเฟรชหน้าแล้วหาย ซึ่งตรงกับที่ควรเป็น (รูปยังไม่ได้อัปโหลด)
 */
let pending: File | null = null;

export function setPendingImage(file: File) {
  pending = file;
}

/** หยิบไฟล์ออกมาครั้งเดียว — หยิบแล้วล้างทิ้ง กันรูปเก่าโผล่ตอนเข้าหน้าใหม่ภายหลัง */
export function takePendingImage(): File | null {
  const f = pending;
  pending = null;
  return f;
}
